#!/usr/bin/env python3
"""Generate an arbitrary-size evaluation split under its own name.

`make_dev_split.py` writes the fixed `dev50` / `dev50_mf` names unconditionally,
whatever `--n` says, and its own docstring warns those must never be
regenerated once stages have landed.  This reuses its sampler and writer so a
differently sized split can be produced without touching them.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path
import sys

import hydra
import numpy as np
from omegaconf import DictConfig

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_dev_split import episode_uid, load_episodes, sample_even, write_split


def build(cfg: DictConfig, name: str, n: int, seed: int) -> None:
    episodes = load_episodes(cfg)
    if not episodes:
        sys.exit("No episodes loaded -- is the dataset downloaded? See data/README.md")

    by_scene: dict = defaultdict(list)
    for episode in episodes:
        by_scene[str(episode.scene_id).split("/")[-1]].append(episode_uid(episode))

    rng = np.random.default_rng(seed)
    uids = sample_even(by_scene, n, rng)
    write_split(
        name,
        uids,
        {
            "header": (
                f"# Representative split: {len(uids)} episodes spread evenly over "
                f"all {len(by_scene)} val scenes (round-robin, seed {seed}).\n"
                f"# Generated by scripts/make_eval_split.py; dev50/dev50_mf untouched."
            ),
            "n_requested": n,
            "seed": seed,
            "scenes": len(by_scene),
        },
    )
    print(f"wrote configs/eval/{name}.yaml and data/splits/{name}.json "
          f"({len(uids)} episodes over {len(by_scene)} scenes)")


def main() -> None:
    ap = argparse.ArgumentParser(add_help=False)
    ap.add_argument("--name", required=True, help="split name, e.g. dev200")
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("-h", "--help", action="store_true")
    args, hydra_argv = ap.parse_known_args()
    if args.help:
        ap.print_help()
        print(__doc__)
        return
    sys.argv = [sys.argv[0], *hydra_argv]

    @hydra.main(config_path="../configs", config_name="config", version_base="1.3")
    def _run(cfg: DictConfig) -> None:
        build(cfg, args.name, args.n, args.seed)

    _run()


if __name__ == "__main__":
    main()
